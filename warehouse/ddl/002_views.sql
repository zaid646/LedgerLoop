-- ExpenseIQ analytics views (drive the "ask about my spend" assistant).

CREATE OR REPLACE VIEW EXPENSEIQ.ANALYTICS.V_SPEND_BY_CATEGORY AS
SELECT CATEGORY, CURRENCY, COUNT(*) AS N,
       SUM(TOTAL_AMOUNT) AS TOTAL_SPEND
FROM EXPENSEIQ.ANALYTICS.EXPENSES
GROUP BY 1, 2;

CREATE OR REPLACE VIEW EXPENSEIQ.ANALYTICS.V_SPEND_BY_MONTH AS
SELECT DATE_TRUNC('month', CREATED_AT) AS MONTH,
       CATEGORY,
       SUM(TOTAL_AMOUNT) AS TOTAL_SPEND,
       SUM(IFF(ESCALATED, 1, 0)) AS ESCALATED_COUNT
FROM EXPENSEIQ.ANALYTICS.EXPENSES
GROUP BY 1, 2;

CREATE OR REPLACE VIEW EXPENSEIQ.ANALYTICS.V_TOP_MERCHANTS AS
SELECT MERCHANT, SUM(TOTAL_AMOUNT) AS TOTAL_SPEND, COUNT(*) AS N
FROM EXPENSEIQ.ANALYTICS.EXPENSES
GROUP BY 1
ORDER BY TOTAL_SPEND DESC
LIMIT 50;

-- Grounding for the assistant: example natural-language -> SQL pairs.
CREATE OR REPLACE VIEW EXPENSEIQ.ANALYTICS.V_SPEND_AUDIT AS
SELECT CATEGORY,
       SUM(TOTAL_AMOUNT) AS TOTAL_SPEND,
       ROUND(AVG(COST_USD), 6) AS AVG_AI_COST,
       COUNT(DISTINCT PROMPT_VERSION) AS PROMPT_VERSIONS
FROM EXPENSEIQ.ANALYTICS.EXPENSES
GROUP BY 1
ORDER BY TOTAL_SPEND DESC;
